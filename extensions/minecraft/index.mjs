import { spawn } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { serve, ok, fail, run, formatRun } from '../sdk.mjs'

const STATE = '.ks-minecraft.json'
const LOG = 'server.log'

function safeJoin(root, rel = '.') {
  const abs = path.resolve(root, rel || '.')
  if (abs !== root && !abs.startsWith(root + path.sep)) throw new Error(`path escapes project: ${rel}`)
  return abs
}

function writeFile(root, rel, content) {
  const abs = safeJoin(root, rel)
  fs.mkdirSync(path.dirname(abs), { recursive: true })
  fs.writeFileSync(abs, content, 'utf8')
}

function javaName(value, fallback) {
  const raw = typeof value === 'string' && value.trim() ? value.trim() : fallback
  const clean = raw.replace(/[^A-Za-z0-9_]/g, '')
  return clean || fallback
}

function javaPackage(value, fallback) {
  const raw = typeof value === 'string' && value.trim() ? value.trim() : fallback
  const clean = raw
    .split('.')
    .map((part) => part.replace(/[^A-Za-z0-9_]/g, ''))
    .filter(Boolean)
    .join('.')
  return clean || fallback
}

function readState(root) {
  const statePath = path.join(root, STATE)
  if (!fs.existsSync(statePath)) return null
  try {
    const state = JSON.parse(fs.readFileSync(statePath, 'utf8'))
    if (!state.pid) return null
    process.kill(state.pid, 0)
    return state
  } catch {
    return null
  }
}

function tail(file, lines = 40) {
  if (!fs.existsSync(file)) return ''
  return fs.readFileSync(file, 'utf8').split('\n').slice(-lines).join('\n')
}

function findJar(root) {
  const libs = path.join(root, 'build', 'libs')
  if (!fs.existsSync(libs)) return null
  const jar = fs.readdirSync(libs).find((name) => name.endsWith('.jar') && !name.includes('sources'))
  return jar ? path.join(libs, jar) : null
}

serve({
  async call(name, args, params) {
    const project = path.resolve(params.projectPath ?? '')
    if (!fs.existsSync(project)) return fail(`project not found: ${project}`)

    if (name === 'plugin_scaffold') {
      const root = safeJoin(project, typeof args.path === 'string' ? args.path : 'plugin')
      const pluginName = javaName(args.name, 'ExamplePlugin')
      const pkg = javaPackage(args.packageName, `com.example.${pluginName.toLowerCase()}`)
      const mcVersion = typeof args.mcVersion === 'string' && args.mcVersion.trim() ? args.mcVersion.trim() : '1.21.4'
      const apiVersion = typeof args.apiVersion === 'string' && args.apiVersion.trim() ? args.apiVersion.trim() : '1.21'
      const mainClass = `${pkg}.${pluginName}`
      const javaDir = path.join(root, 'src', 'main', 'java', ...pkg.split('.'))

      writeFile(
        root,
        'settings.gradle',
        `rootProject.name = '${pluginName}'\n`
      )
      writeFile(
        root,
        'build.gradle',
        `plugins {\n    id 'java'\n}\n\ngroup = '${pkg}'\nversion = '1.0.0'\n\nrepositories {\n    mavenCentral()\n    maven { url = 'https://repo.papermc.io/repository/maven-public/' }\n}\n\ndependencies {\n    compileOnly 'io.papermc.paper:paper-api:${mcVersion}-R0.1-SNAPSHOT'\n}\n\njava {\n    toolchain {\n        languageVersion = JavaLanguageVersion.of(21)\n    }\n}\n\ntasks.withType(JavaCompile).configureEach {\n    options.encoding = 'UTF-8'\n}\n\nprocessResources {\n    filesMatching('plugin.yml') {\n        expand(version: version)\n    }\n}\n`
      )
      writeFile(
        root,
        'src/main/resources/plugin.yml',
        `name: ${pluginName}\nversion: '\${version}'\nmain: ${mainClass}\napi-version: '${apiVersion}'\ndescription: Generated by KS Agent\ncommands:\n  hello:\n    description: Say hello from ${pluginName}\n    usage: /hello\n`
      )
      fs.mkdirSync(javaDir, { recursive: true })
      fs.writeFileSync(
        path.join(javaDir, `${pluginName}.java`),
        `package ${pkg};\n\nimport org.bukkit.ChatColor;\nimport org.bukkit.command.Command;\nimport org.bukkit.command.CommandSender;\nimport org.bukkit.plugin.java.JavaPlugin;\n\npublic final class ${pluginName} extends JavaPlugin {\n    @Override\n    public void onEnable() {\n        getLogger().info("${pluginName} enabled");\n    }\n\n    @Override\n    public void onDisable() {\n        getLogger().info("${pluginName} disabled");\n    }\n\n    @Override\n    public boolean onCommand(CommandSender sender, Command command, String label, String[] args) {\n        if (!command.getName().equalsIgnoreCase("hello")) return false;\n        sender.sendMessage(ChatColor.GREEN + "Hello from ${pluginName}!");\n        return true;\n    }\n}\n`,
        'utf8'
      )
      return ok(
        `Created Paper plugin ${pluginName} (${pkg}) in ${path.relative(project, root) || '.'}\n` +
          `Paper API: ${mcVersion}\nNext: ext_minecraft_plugin_build, then drop the jar into server/plugins and run ext_minecraft_server_start.`
      )
    }

    if (name === 'plugin_build') {
      const root = safeJoin(project, typeof args.path === 'string' ? args.path : 'plugin')
      if (!fs.existsSync(path.join(root, 'build.gradle'))) return fail('build.gradle not found; run plugin_scaffold first')
      const wrapper = path.join(root, 'gradlew')
      const result = fs.existsSync(wrapper)
        ? await run('sh', ['./gradlew', 'build', '--no-daemon'], { cwd: root, timeoutMs: 900_000 })
        : await run('gradle', ['build', '--no-daemon'], { cwd: root, timeoutMs: 900_000 })
      if (result.code !== 0) return fail(formatRun(result))
      const jar = findJar(root)
      return ok(`${formatRun(result)}\n\njar: ${jar ? path.relative(project, jar) : '(not found)'}`)
    }

    if (name === 'server_start') {
      const root = safeJoin(project, typeof args.path === 'string' ? args.path : 'server')
      fs.mkdirSync(root, { recursive: true })
      const jarName = typeof args.jar === 'string' && args.jar.trim() ? args.jar.trim() : 'server.jar'
      const jarPath = safeJoin(root, jarName)
      if (!fs.existsSync(jarPath)) {
        return fail(`server jar not found: ${path.relative(project, jarPath)}\nDownload Paper/Spigot into that path first.`)
      }
      const existing = readState(root)
      if (existing) return ok(`server already running (pid ${existing.pid})`)
      if (args.eula === true) fs.writeFileSync(path.join(root, 'eula.txt'), 'eula=true\n', 'utf8')
      const memory = Math.min(16384, Math.max(512, Number(args.memoryMb) || 2048))
      const logPath = path.join(root, LOG)
      const out = fs.openSync(logPath, 'a')
      const child = spawn('java', [`-Xmx${memory}M`, '-Xms512M', '-jar', jarPath, 'nogui'], {
        cwd: root,
        detached: true,
        stdio: ['ignore', out, out],
        env: { ...process.env }
      })
      child.on('error', (error) => {
        fs.appendFileSync(logPath, `\n[ks-agent] spawn error: ${error.message}\n`)
      })
      child.unref()
      const state = { pid: child.pid, jar: jarName, memoryMb: memory, startedAt: Date.now() }
      fs.writeFileSync(path.join(root, STATE), JSON.stringify(state, null, 2))
      return ok(
        `Started Minecraft server (pid ${child.pid}, ${memory} MB). Logs: ${path.relative(project, logPath)}\n` +
          `Use ext_minecraft_server_status to watch startup. If it exits immediately, check the log (Java version, EULA, jar name).`
      )
    }

    if (name === 'server_stop') {
      const root = safeJoin(project, typeof args.path === 'string' ? args.path : 'server')
      const state = readState(root)
      if (!state) return fail('server is not running')
      try {
        process.kill(-state.pid, 'SIGTERM')
      } catch {
        try {
          process.kill(state.pid, 'SIGTERM')
        } catch {
          // already gone
        }
      }
      fs.rmSync(path.join(root, STATE), { force: true })
      return ok(`Stopped server (pid ${state.pid})`)
    }

    if (name === 'server_status') {
      const root = safeJoin(project, typeof args.path === 'string' ? args.path : 'server')
      const state = readState(root)
      const log = tail(path.join(root, LOG))
      if (!state) return ok(`server is not running${log ? `\n\nlast log:\n${log}` : ''}`)
      return ok(`running (pid ${state.pid}, ${state.memoryMb} MB)\n\nlast log:\n${log}`)
    }

    if (name === 'bot_install') {
      const root = safeJoin(project, typeof args.path === 'string' ? args.path : 'bot')
      fs.mkdirSync(root, { recursive: true })
      if (!fs.existsSync(path.join(root, 'package.json'))) {
        fs.writeFileSync(
          path.join(root, 'package.json'),
          JSON.stringify({ name: 'ks-minecraft-bot', private: true, type: 'module', dependencies: {} }, null, 2) + '\n'
        )
      }
      const result = await run('npm', ['install', 'mineflayer'], { cwd: root, timeoutMs: 900_000 })
      return result.code === 0 ? ok(formatRun(result)) : fail(formatRun(result))
    }

    if (name === 'bot_harness') {
      const root = safeJoin(project, typeof args.path === 'string' ? args.path : 'bot')
      const host = typeof args.host === 'string' && args.host.trim() ? args.host.trim() : '127.0.0.1'
      const port = Math.min(65535, Math.max(1, Number(args.port) || 25565))
      const username = typeof args.username === 'string' && args.username.trim() ? args.username.trim() : 'KS_Bot'
      const version = typeof args.version === 'string' ? args.version.trim() : ''
      fs.mkdirSync(root, { recursive: true })
      const packagePath = path.join(root, 'package.json')
      if (!fs.existsSync(packagePath)) {
        fs.writeFileSync(
          packagePath,
          JSON.stringify(
            { name: 'ks-minecraft-bot', private: true, type: 'module', dependencies: { mineflayer: '^4.23.0' } },
            null,
            2
          ) + '\n'
        )
      }
      writeFile(
        root,
        'bot.mjs',
        `import mineflayer from 'mineflayer'\n\nconst options = {\n  host: ${JSON.stringify(host)},\n  port: ${port},\n  username: ${JSON.stringify(username)},\n  auth: 'offline',\n${version ? `  version: ${JSON.stringify(version)},\n` : ''}}\n\nconst bot = mineflayer.createBot(options)\nlet done = false\n\nfunction finish(code = 0) {\n  if (done) return\n  done = true\n  try { bot.quit() } catch {}\n  setTimeout(() => process.exit(code), 250)\n}\n\nbot.once('spawn', () => {\n  console.log('spawned as', bot.username, 'at', bot.entity.position.toString())\n  setTimeout(() => {\n    console.log('health', bot.health, 'food', bot.food)\n    finish(0)\n  }, 4000)\n})\n\nbot.on('error', (error) => {\n  console.error('bot error:', error.message)\n  finish(1)\n})\n\nbot.on('end', (reason) => {\n  console.log('disconnected:', reason)\n  finish(0)\n})\n\nsetTimeout(() => {\n  console.error('bot timed out')\n  finish(1)\n}, 15000)\n`
      )
      return ok(`Wrote ${path.relative(project, path.join(root, 'bot.mjs'))}\nNext: ext_minecraft_bot_install, then ext_minecraft_bot_run.`)
    }

    if (name === 'bot_run') {
      const root = safeJoin(project, typeof args.path === 'string' ? args.path : 'bot')
      if (!fs.existsSync(path.join(root, 'bot.mjs'))) return fail('bot.mjs not found; run bot_harness first')
      if (!fs.existsSync(path.join(root, 'node_modules', 'mineflayer'))) return fail('mineflayer missing; run bot_install first')
      const timeoutMs = Math.min(120_000, Math.max(5000, Number(args.timeoutMs) || 20_000))
      const result = await run('node', ['bot.mjs'], { cwd: root, timeoutMs })
      return result.code === 0 ? ok(formatRun(result)) : fail(formatRun(result))
    }

    return fail(`unknown tool: ${name}`)
  }
})
